"""Write the project's defaults out as an editable Hydra config folder.

Every setting lives in the hydra-zen store, which is Python: readable only by running
the app with ``--cfg job``, and not something a user can keep under version control
next to their data. This dumps one complete config per console script into a directory
that ``--config-dir`` then reads back.

The dumped files are deliberately *not* named after the store entries they came from.
Hydra's automatic schema matching — where a YAML file inherits the structured config of
the same name — was removed after 1.1, and for the entries carrying a defaults list
(``pipeline`` and ``report``) a same-named file is a hard error rather than a warning.
Naming each file after its command sidesteps the collision entirely and reads better on
the command line.
"""

from __future__ import annotations

from pathlib import Path

from hydra import compose, initialize_config_module
from hydra_zen import store
from loguru import logger
from omegaconf import OmegaConf

import clearml_yolo.configs  # noqa: F401  registers every config

# Config name in the store -> file name in the dumped folder, which is the command that
# reads it. `cy` composes all four stages; the rest are the standalone apps.
COMMAND_OF_CONFIG = {
    "pipeline": "cy",
    "train": "cy-train",
    "predict": "cy-predict",
    "metrics": "cy-metrics",
    "report": "cy-report",
    "compare": "cy-compare",
    "ground_truth": "cy-ground-truth",
}

HEADER = """# Generated by `cy-init-config`. Edit freely, then run:
#     uv run {command} --config-dir {directory} --config-name {name}
#
# ${{...}} entries are Hydra interpolations, not placeholders: they are what makes one
# clearml.task_name on the command line name every stage of the run. Resolving them by
# hand would break that.
"""


def _composed(config_name: str) -> str:
    """Compose one app's config exactly as its CLI would, leaving interpolations intact."""
    with initialize_config_module(config_module="hydra_zen.wrapper", version_base="1.3"):
        config = compose(config_name=config_name)
    # resolve=False keeps ${clearml.project_name} as a live reference rather than
    # freezing today's value into the file.
    return str(OmegaConf.to_yaml(config, resolve=False))


def dump_config_tree(directory: str | Path, *, overwrite: bool = False) -> list[Path]:
    """Write one complete, editable config file per console script into ``directory``."""
    store.add_to_hydra_store(overwrite_ok=True)
    target = Path(directory).expanduser()
    target.mkdir(parents=True, exist_ok=True)

    registered = {entry["name"] for entry in store if entry["group"] is None}
    written: list[Path] = []
    for config_name, command in COMMAND_OF_CONFIG.items():
        if config_name not in registered:
            logger.warning("No config registered under {!r}; skipping it", config_name)
            continue
        path = target / f"{command}.yaml"
        if path.exists() and not overwrite:
            raise FileExistsError(
                f"{path} already exists. Pass --force to overwrite it, or dump into an "
                "empty directory to keep your edits."
            )
        header = HEADER.format(command=command, directory=target, name=command)
        path.write_text(f"{header}\n{_composed(config_name)}", encoding="utf-8")
        written.append(path)
        logger.info("Wrote {}", path)

    logger.info("Wrote {} config file(s) to {}", len(written), target)
    return written
