"""Export current command defaults as editable Hydra configuration examples."""

import shlex
from pathlib import Path

from hydra import compose, initialize_config_module
from hydra_zen import store
from loguru import logger
from omegaconf import OmegaConf

from clearml_yolo.adapters.storage.filesystem import write_path
from clearml_yolo.adapters.yolo.config import (
    native_defaults,
    prediction_defaults,
    render_native_yaml,
)
from clearml_yolo.core.models import model_preset
from clearml_yolo.entrypoints.hydra.configs import NATIVE_COMMANDS, PREDICTION_COMMANDS
from clearml_yolo.entrypoints.hydra.transforms import (
    TRAINING_COMMANDS,
    native_overlay,
    profile_values,
)

COMMAND_OF_CONFIG = {
    "pipeline": "cy",
    "train": "cy-train",
    "predict": "cy-predict",
    "val": "cy-val",
    "metrics": "cy-metrics",
    "report": "cy-report",
    "compare": "cy-compare",
    "ground_truth": "cy-ground-truth",
    "export": "cy-export",
}


def _header(config_name: str, command: str, directory: Path, model: str = "ultralytics") -> str:
    lines = [
        "# Generated by cy-init-config. Edit this example, then run:",
        (
            f"#   {command} --config-dir {shlex.quote(str(directory.resolve()))} "
            f"--config-name {command}"
        ),
        "# Replace ??? with your required inputs before running.",
        "# Relative input paths are resolved from the working directory.",
        "# Set clearml.project_name, clearml.task_name and clearml.tags for your run.",
        "# Implicit outputs use runs/<safe-project>/<safe-task>-<task-id>/.",
    ]
    if config_name == "pipeline":
        lines.append("# Set run_dir to route all pipeline outputs together.")
    if config_name in {"pipeline", "train"}:
        lines.extend(
            [
                "# CSV training: ground_truth=truth.csv; native detectors use derived COCO data."
                if model != "ultralytics"
                else "# CSV training: ground_truth=truth.csv dataset_format=ndjson (or flat).",
                "# Image paths inside the CSV resolve relative to the CSV directory.",
                "# Cache default: CY_HOME/.cache/clearml-yolo/datasets.",
                "# Set dataset_cache_dir to override the dataset working-copy location.",
                "# Cached images are immutable; invalidate explicitly after source corrections.",
                "# Invalid boxes are dropped and their total is reported before training.",
                "# CSV data overrides native data, class filters, and dataset fractions.",
            ]
        )
    if config_name in {"predict", "val"}:
        lines.append(
            "# Set weights to your trained checkpoint."
            if model != "ultralytics"
            else "# Set weights to your trained checkpoint (or use ultralytics_predict.model)."
        )
    if config_name in NATIVE_COMMANDS and model != "ultralytics":
        lines.append(f"# Model settings: model/{model}.yaml.")
        lines.extend(_detector_header(config_name))
        return "\n".join(lines) + "\n\n"
    if config_name in NATIVE_COMMANDS:
        lines.extend(
            [
                "# Paste upstream native YAML unchanged into ultralytics/default.yaml.",
                "# Override shared values: ultralytics.imgsz=960 ultralytics.epochs=10",
                "# Devices are independent: training=null, prediction=[-1].",
                "# CPU: ultralytics.device=cpu ultralytics_predict.device=cpu",
            ]
        )
    if config_name in PREDICTION_COMMANDS:
        lines.append(
            "# Prediction overrides: ultralytics_predict/default.yaml or CLI "
            "ultralytics_predict.batch=8"
        )
    return "\n".join(lines) + "\n\n"


def _detector_header(config_name: str) -> list[str]:
    if config_name == "export":
        return [
            "# ONNX: weights=best.pth export.operation=onnx export.device=cpu.",
            "# Engine: export.operation=build export.onnx=model.onnx export.device=0.",
            "# Verification also requires weights, export.engine and labeled ground_truth.",
            "# Select export.precision=fp32 or fp16 for engine build and verification.",
        ]
    lines = ["# Prediction controls: model.predict.batch=8 model.predict.device=cpu."]
    if config_name in {"pipeline", "train"}:
        lines.append("# Training controls: model.train.epochs=10 model.train.device=cpu.")
    return lines


def _check_destinations(paths: list[Path], *, overwrite: bool) -> None:
    """Preflight files and their parents before writing any example."""
    for path in paths:
        for parent in path.parents:
            if parent.is_symlink() or (parent.exists() and not parent.is_dir()):
                raise FileExistsError(f"{parent} is not a regular directory")
        if path.exists() or path.is_symlink():
            if not overwrite:
                raise FileExistsError(f"{path} already exists. Pass --force to overwrite examples.")
            if path.is_symlink() or not path.is_file():
                raise FileExistsError(f"{path} is not a regular file; choose another directory.")


def _selection(command: str, model: str | None) -> tuple[str, str]:
    config_of_command = {public: schema for schema, public in COMMAND_OF_CONFIG.items()}
    if command not in config_of_command:
        raise ValueError(f"Unknown command {command!r}; choose from {', '.join(config_of_command)}")
    config_name = config_of_command[command]
    model = model or ("fasterrcnn/resnet50_fpn" if config_name == "export" else "ultralytics")
    if config_name == "export" and model_preset(model).backend != "fasterrcnn":
        raise ValueError("cy-export supports only Faster R-CNN presets")
    if model != "ultralytics" and config_name not in NATIVE_COMMANDS:
        raise ValueError(f"{command} does not execute a model")
    return config_name, model


def _groups(config_name: str, model: str) -> dict[Path, str]:
    selected = model_preset(model)
    groups: dict[Path, str] = {}
    if config_name in TRAINING_COMMANDS:
        for profile in ("default", "albumentations"):
            groups[Path("transforms") / f"{profile}.yaml"] = OmegaConf.to_yaml(
                OmegaConf.create(profile_values(profile))
            )
            groups[Path("transform_overrides") / f"{model}_{profile}.yaml"] = (
                "# @package _global_\n"
                + OmegaConf.to_yaml(OmegaConf.create(native_overlay(model, profile)))
            )
    if config_name in NATIVE_COMMANDS and model != "ultralytics":
        groups[Path("model") / f"{model}.yaml"] = OmegaConf.to_yaml(
            OmegaConf.create(selected.model_dump(mode="json"))
        )
    if config_name in NATIVE_COMMANDS and model == "ultralytics":
        groups[Path("ultralytics/default.yaml")] = render_native_yaml(
            native_defaults(), "train", example=True
        )
    if config_name in PREDICTION_COMMANDS and model == "ultralytics":
        groups[Path("ultralytics_predict/default.yaml")] = (
            "# Shared references remain editable; use a literal to override a reference.\n"
            + render_native_yaml(prediction_defaults(), "predict", example=True)
        )
    return groups


def _command_yaml(config_name: str, model: str) -> str:
    store.add_to_hydra_store(overwrite_ok=True)
    with initialize_config_module(config_module="hydra_zen.wrapper", version_base="1.3"):
        overrides = [f"model={model}"] if config_name in NATIVE_COMMANDS else []
        config = compose(config_name=config_name, overrides=overrides)
        # Reference the registered command schema to keep inherited values lazy;
        # group YAML remains plain native YAML and can be pasted unchanged.
        values = OmegaConf.to_container(config, resolve=False)
        if not isinstance(values, dict):
            raise TypeError("Command configuration must be a mapping")
        values.pop("ultralytics", None)
        values.pop("ultralytics_predict", None)
        values.pop("model", None)
        values.pop("transforms", None)
        defaults: list[object] = [config_name]
        if config_name in NATIVE_COMMANDS and model != "ultralytics":
            defaults.append({"override /model": model})
        if config_name in NATIVE_COMMANDS and model == "ultralytics":
            defaults.append({"override /ultralytics": "default"})
        if config_name in PREDICTION_COMMANDS and model == "ultralytics":
            defaults.append({"override /ultralytics_predict": "default"})
        defaults.append("_self_")
        example = OmegaConf.create({"defaults": defaults, **values})
        return str(OmegaConf.to_yaml(example, resolve=False))


def dump_config_tree(
    directory: str | Path,
    *,
    command: str = "cy",
    model: str | None = None,
    overwrite: bool = False,
) -> list[Path]:
    """Write the selected command and its required groups, preserving files by default."""
    config_name, selection = _selection(command, model)
    target = write_path(directory)
    contents = {
        Path(f"{command}.yaml"): _header(config_name, command, target, selection)
        + _command_yaml(config_name, selection),
        **_groups(config_name, selection),
    }
    paths = [target / path for path in contents]
    _check_destinations(paths, overwrite=overwrite)

    target.mkdir(parents=True, exist_ok=True)
    for path, content in zip(paths, contents.values(), strict=True):
        path.parent.mkdir(parents=True, exist_ok=True)
        # Exclusive creation also protects files created after the initial preflight.
        with path.open("w" if overwrite else "x", encoding="utf-8") as stream:
            stream.write(content)
        logger.info("Wrote {}", path)
    return paths
