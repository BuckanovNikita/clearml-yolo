def _stable(value: Any) -> Any:
    if isinstance(value, float) and not math.isfinite(value):
        return "NaN" if math.isnan(value) else str(value)
    if isinstance(value, dict):
        return {str(key): _stable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_stable(item) for item in value]
    if isinstance(value, (set, frozenset)):
        return [_stable(item) for item in sorted(value)]
    return value


def _frame(frame: pd.DataFrame) -> Any:
    return json.loads(frame.to_json(orient="split", double_precision=15))


def _stable_mapping(value: dict[str, Any]) -> dict[str, Any]:
    return {key: _stable(item) for key, item in value.items()}


def _canonical_scientific(value: dict[str, Any]) -> dict[str, Any]:
    # Image traversal uses a set in the original matcher. Preserve relationships
    # while ignoring its process-specific ordering and generated ordinal IDs.
    value["payload"]["matches"].sort(key=lambda item: json.dumps(item, sort_keys=True))
    rows = value["result_rows"]
    for column, name in enumerate(rows["columns"]):
        if name not in {"matches_pre_threshold", "matches_post_threshold"}:
            continue
        for row in rows["data"]:
            relations = json.loads(row[column])
            for relation in relations:
                relation.pop("match_id")
            row[column] = sorted(relations, key=lambda item: json.dumps(item, sort_keys=True))
    return value


def _expected(section: str) -> Any:
    return json.loads(BASELINE.read_text(encoding="utf-8"))[section]


def _scientific_observation(strategy: str, method: str, empty: bool) -> dict[str, Any]:
    truth = prepare_ground_truth(
        pd.DataFrame(
            [
                ("1", "0001", 0, 0, 10, 10),
                ("1", "0001", 7, 0, 17, 10),
                ("2", "0001", 0, 0, 10, 10),
                ("2", "1", 20, 0, 30, 10),
                ("3", None, None, None, None, None),
            ],
            columns=COLUMNS,
        ).assign(split="test"),
        deduplicate=False,
    )
    predictions = pd.DataFrame(
        [
            ("1", "0001", 2, 0, 12, 10, 0.9),
            ("1", "0001", 0, 0, 10, 10, 0.8),
            ("1", "0001", 7, 0, 17, 10, 0.8),
            ("3", "0001", 0, 0, 10, 10, 0.8),
            ("2", "0001", 0, 0, 10, 10, 0.5),
            ("2", "1", 20, 0, 30, 10, 0.5),
            ("3", "кошка", 0, 0, 10, 10, 0.7),
        ],
        columns=[*COLUMNS, "confidence"],
    )
    if empty:
        predictions = predictions.iloc[:0]
    prepared = prepare_predictions(
        predictions,
        preprocess_conf_threshold=None,
        preprocess_nms_containment_threshold=None,
        preprocess_nms_iou_threshold=None,
    )
    evaluated = compute_evaluation(
        truth,
        predictions,
        prepared,
        split="test",
        classes=["0001", "1", "кошка"],
        thresholds={"0001": 0.5, "1": 0.5, "кошка": 0.7},
        required_classes=None,
        iou_threshold=0.5,
        matching_strategy=strategy,
        ap_method=method,
        skip_cohen_kappa=True,
    )
    return _canonical_scientific(
        _stable_mapping(
            {
                "metrics": {
                    name: metric.model_dump() for name, metric in evaluated.metrics.items()
                },
                "counts": {
                    name: count.model_dump() for name, count in evaluated.outcome.counts.items()
                },
                "gt_status": _frame(evaluated.outcome.gt_status),
                "pred_status": _frame(evaluated.outcome.pred_status),
                "curves": [curve.model_dump() for curve in evaluated.pr_curves],
                "confusion": evaluated.confusion_matrix.model_dump(),
                "payload": evaluated.evaluation_payload.model_dump(),
                "result_rows": _frame(evaluated.result_rows),
            }
        )
    )


