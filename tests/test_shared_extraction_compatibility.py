def _paired_outcome(candidate: bool) -> SplitOutcome:
    gt_rows = []
    pred_rows = []
    counts = {}
    for class_index, label in enumerate(["0001", "1", "кошка"]):
        for image in range(8):
            detected = (image + class_index) % (2 if candidate else 3) == 0
            gt_rows.append(
                {
                    "gt_index": class_index * 8 + image,
                    "image_name": str(image),
                    "instance_label": label,
                    "detected": detected,
                }
            )
            pred_rows.append(
                {
                    "pred_index": class_index * 8 + image,
                    "image_name": str(image),
                    "instance_label": label,
                    "is_tp": detected,
                }
            )
        hits = sum(bool(row["detected"]) for row in gt_rows if row["instance_label"] == label)
        counts[label] = ClassCounts(tp=hits, fp=8 - hits, fn=8 - hits)
    return SplitOutcome(counts, pd.DataFrame(gt_rows), pd.DataFrame(pred_rows))


def _comparison_observation() -> tuple[dict[str, Any], Any]:
    baseline, candidate = _paired_outcome(False), _paired_outcome(True)
    images = [str(image) for image in range(8)] + ["background"]
    tables = build_comparison_rows(
        baseline,
        candidate,
        thresholds_baseline={"0001": 0.3, "1": 0.4},
        thresholds_candidate={"0001": 0.35, "кошка": 0.7},
        images=images,
        baseline_classes={"0001", "1"},
        candidate_classes={"0001", "кошка"},
        iterations=127,
        seed=93,
        q=0.1,
    )
    return _stable(
        {
            "precision": bootstrap_precision_delta(
                baseline.pred_status, candidate.pred_status, images, iterations=127, seed=93
            ).model_dump(),
            "recall": bootstrap_recall_delta(
                baseline.gt_status, candidate.gt_status, images, iterations=127, seed=93
            ).model_dump(),
            "mcnemar": mcnemar_recall(
                baseline.gt_status.set_index("gt_index")["detected"],
                candidate.gt_status.set_index("gt_index")["detected"],
            ).model_dump(),
            "bh": adjust_benjamini_hochberg([0.02, math.nan, 0.02, 0.8], q=0.1).model_dump(),
            "rows": _frame(tables.rows),
            "excluded": _frame(tables.excluded),
            "methodology": tables.methodology,
        }
    ), tables


def test_paired_statistics_and_one_sided_tables_equal_frozen_values() -> None:
    observed, _ = _comparison_observation()
    assert observed == _expected("comparison")


def _xml(value: Any) -> str:
    return ET.tostring(value.to_tree(), encoding="unicode")


def _workbook_observation(path: Path) -> dict[str, Any]:
    """Read cell values/types, resolved styles and layout; ignore ZIP timestamps."""
    workbook = load_workbook(path, data_only=False)
    styles: list[Any] = []
    sheets = []
    try:
        for sheet in workbook:
            cells = []
            for row in sheet:
                for cell in row:
                    if cell.value is None and not cell.has_style:
                        continue
                    style = [
                        _xml(cell.font),
                        _xml(cell.fill),
                        _xml(cell.border),
                        _xml(cell.alignment),
                        _xml(cell.protection),
                        cell.number_format,
                    ]
                    if style not in styles:
                        styles.append(style)
                    cells.append([cell.coordinate, cell.value, cell.data_type, styles.index(style)])
            sheets.append(
                {
                    "name": sheet.title,
                    "state": sheet.sheet_state,
                    "cells": cells,
                    "merged": sorted(str(item) for item in sheet.merged_cells.ranges),
                    "freeze": sheet.freeze_panes,
                    "columns": {key: _xml(value) for key, value in sheet.column_dimensions.items()},
                    "rows": {str(key): dict(value) for key, value in sheet.row_dimensions.items()},
                    "print_area": str(sheet.print_area),
                    "print_rows": sheet.print_title_rows,
                    "print_columns": sheet.print_title_cols,
                    "page_setup": _xml(sheet.page_setup),
                    "page_margins": _xml(sheet.page_margins),
                    "print_options": _xml(sheet.print_options),
                    "sheet_properties": _xml(sheet.sheet_properties),
                    "views": _xml(sheet.views),
                }
            )
        with ZipFile(path) as archive:
            drawings = {
                name: ET.tostring(
                    ET.fromstring(archive.read(name)),  # noqa: S314 - generated fixture OOXML
                    encoding="unicode",
                )
                for name in sorted(archive.namelist())
                if name.startswith(("xl/charts/", "xl/drawings/")) and name.endswith(".xml")
            }
        return _stable_mapping(
            {
                "sheets": sheets,
                "styles": styles,
                "drawings": drawings,
                "defined_names": [_xml(value) for value in workbook.defined_names.values()],
            }
        )
    finally:
        workbook.close()


def _report_inputs(directory: Path) -> tuple[Path, Path]:
    paths = []
    for model, labels, scores in [
        ("candidate", ["0001", "1", "new", "low"], [0.8, 0.0, 0.4, 0.9]),
        ("baseline", ["0001", "1", "old", "low"], [0.6, None, 0.2, 0.5]),
    ]:
        path = directory / f"{model}.xlsx"
        pd.DataFrame(
            {
                "Класс": labels,
                "ID": [10, 11, 12, 13],
                "Количество примеров train": [30, 30, 30, 2],
                "f1_score": scores,
                "ap50": scores,
                "perebrak": [0.0, 0.3, 0.7, 0.1],
                "nedobrak": [0.0, 0.2, 0.5, 0.1],
            }
        ).to_excel(path, index=False)
        paths.append(path)
    return paths[0], paths[1]


def _reports_observation(directory: Path, custom: bool) -> dict[str, Any]:
    candidate, baseline = _report_inputs(directory)
    config_path = None
    if custom:
        config_path = directory / "custom.yaml"
        config_path.write_text(
            "min_train_count: 3\ndegradation_threshold: 0.1\n"
            "colors:\n  header: AABBCC\n"
            "sheet_names:\n  model1: Candidate\n  model2: Baseline\n"
            "  comparison: Difference\n  excluded: Excluded\n  verdict: Verdict\n"
            "business:\n  target_perebrak: 0.4\n  target_nedobrak: 0.25\n"
            "  column_translations:\n    f1_score: F1 custom\n    ap50: AP custom\n",
            encoding="utf-8",
        )
    dev, business = directory / "dev.xlsx", directory / "business.xlsx"
    build_reports(candidate, baseline, dev, business, config_path)
    return {"dev": _workbook_observation(dev), "business": _workbook_observation(business)}


